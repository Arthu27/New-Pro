def build_setup_faq(query=''):
    """Пошаговый ответ на вопрос «как настроить X?».

    query — текст вопроса (любой регистр). Если тема не распознана,
    возвращаем обзор всех направлений настройки с подсказкой уточнить.
    """
    key = ('setup', (query or '').strip().lower()[:120])
    hit = _cached(key)
    if hit is not None:
        return hit

    q = (query or '').lower()
    picked = [(title, steps) for keys, title, steps in _SETUP_TOPICS
              if any(k in q for k in keys)]

    lines = []
    if picked:
        lines.append('Вот как это настроить, по шагам:')
        for title, steps in picked[:2]:
            lines.append('')
            lines.append(f'▸ {title}')
            for i, step in enumerate(steps, 1):
                lines.append(f'  {i}. {step}')
        lines.append('')
        lines.append('Если хочешь настроить что-то ещё — просто напиши, '
                     'например «как настроить варны» или «как настроить тикеты» '
                     '— распишу так же по шагам.')
    else:
        lines.append('С удовольствием помогу настроить! Вот главные '
                     'направления — напиши, что именно нужно:')
        lines.append('')
        for _keys, title, _steps in _SETUP_TOPICS:
            lines.append(f'▸ {title}')
        lines.append('')
        lines.append('Примеры вопросов: «как настроить щит сервера», «как '
                     'настроить варны», «как настроить каналы», «как настроить '
                     'автороль» — отвечу по шагам.')
    return _store(key, '\n'.join(lines))


def build_setup_digest():
    """Компактный путеводитель для системного промпта LLM (в одну строку
    на тему): чтобы живой ИИ тоже точно знал, где что настраивается."""
    key = ('setup-digest',)
    hit = _cached(key)
    if hit is not None:
        return hit
    lines = [
        'ЕСЛИ СПРАШИВАЮТ «КАК НАСТРОИТЬ» — отвечай по шагам и называй точные '
        'страницы панели. Путеводитель (тема → где настраивается):',
    ]
    for _keys, title, steps in _SETUP_TOPICS:
        first = steps[0].strip().rstrip('.')
        lines.append(f'- {title}: {first}.')
    lines.append('Подробные шаги этих гайдов известны — давай их по запросу '
                 '«как настроить ...», не выдумывая других путей.')
    return _store(key, '\n'.join(lines))
